import test from 'node:test';
import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { spawn } from 'node:child_process';
import { once } from 'node:events';
import { setTimeout as sleep } from 'node:timers/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import net from 'node:net';
import { createPool, migrate } from '../../src/db.js';
import { Broker } from '../../src/queue.js';

test('isolated PostgreSQL 16 + JetStream + separate Web/Worker processes', {skip:process.env.RUN_INTEGRATION !== '1',timeout:240000},async t=>{
  const databaseUrl=process.env.TEST_DATABASE_URL, natsUrl=process.env.TEST_NATS_URL;
  if (!databaseUrl || !natsUrl) throw new Error('TEST_DATABASE_URL and TEST_NATS_URL required');
  if (!/^workerlab_test(?:_[a-zA-Z0-9_]+)?$/.test(new URL(databaseUrl).pathname.slice(1))) throw new Error('Integration refuses a non-test database');
  const namespace=`ci_${randomUUID().replaceAll('-','').slice(0,16)}`;
  const pool=createPool({databaseUrl,role:'integration'}), broker=new Broker({natsUrl,namespace}), children=[];
  t.after(async()=>{
    for (const child of children) if(child.exitCode===null && child.signalCode===null) child.kill('SIGKILL');
    await Promise.allSettled(children.map(child=>child.exitCode===null && child.signalCode===null ? once(child,'exit') : Promise.resolve()));
    await broker.close().catch(()=>{}); await pool.end();
  });
  await migrate(pool); await migrate(pool);
  const until=async(work,timeout=70000)=>{const deadline=Date.now()+timeout;let value;while(Date.now()<deadline){try{value=await work();if(value)return value;}catch{}await sleep(1000);}throw new Error('Integration condition timed out');};
  await until(async()=>{try{await broker.open();return true;}catch{return false;}},20000);
  await broker.setup(); await broker.setup();
  const tempServer=net.createServer();await new Promise(resolve=>tempServer.listen(0,'127.0.0.1',resolve));const port=tempServer.address().port;await new Promise(resolve=>tempServer.close(resolve));
  const token='ci-only-workerlab-api-token-not-for-production-123456';
  const common={...process.env,DATABASE_URL:databaseUrl,NATS_URL:natsUrl,QUEUE_NAMESPACE:namespace,API_TOKEN:token,HOST:'127.0.0.1',PORT:String(port),RUN_MIGRATIONS_ON_START:'false',QUEUE_AUTO_SETUP:'false',WORKER_CONCURRENCY:'1'};
  const start=role=>{const child=spawn(process.execPath,['src/start.js'],{env:{...common,APP_ROLE:role,WORKER_HEALTH_FILE:path.join(tmpdir(),`workerlab-${randomUUID()}.json`)},stdio:['ignore','pipe','pipe']});children.push(child);child.stdout.on('data',()=>{});child.stderr.on('data',()=>{});return child;};
  const web=start('web'), worker=start('worker');
  const base=`http://127.0.0.1:${port}`;
  const request=async(route,body,key=randomUUID())=>{const r=await fetch(base+route,{method:body?'POST':'GET',headers:{Authorization:`Bearer ${token}`,'Content-Type':'application/json','Idempotency-Key':key},body:body?JSON.stringify(body):undefined});const value=await r.json();assert.ok(r.ok,`HTTP ${r.status}`);return value;};
  await until(async()=>{const r=await fetch(base+'/health/ready');return r.ok;});
  const key=randomUUID(), echo={type:'echo',payload:{text:'<script>inert text</script>'}};
  const first=await request('/api/jobs',echo,key), duplicate=await request('/api/jobs',echo,key);
  assert.equal(duplicate.job.id,first.job.id);assert.equal(duplicate.duplicate,true);
  let detail=await until(async()=>{const value=await request(`/api/jobs/${first.job.id}`);return value.status==='completed'?value:false;});
  assert.equal(detail.effectCount,1);assert.equal(detail.result.text,echo.payload.text);
  await broker.publish({kind:'job',body:{jobId:first.job.id},message_id:`redelivery-test:${randomUUID()}`});
  await sleep(1000);assert.equal((await request(`/api/jobs/${first.job.id}`)).effectCount,1);
  const retry=await request('/api/jobs',{type:'fail-first',payload:{failures:2}});
  detail=await until(async()=>{const value=await request(`/api/jobs/${retry.job.id}`);return value.status==='completed'?value:false;});
  assert.equal(detail.attempt_count,3);assert.equal(detail.attempts.filter(a=>a.status==='failed').length,2);
  const fail=await request('/api/jobs',{type:'always-fail',payload:{}});
  detail=await until(async()=>{const value=await request(`/api/jobs/${fail.job.id}`);return value.status==='failed'&&value.deadLetter?.delivered_at?value:false;});
  assert.equal(detail.attempt_count,3);assert.equal(detail.effectCount,0);
  assert.ok((await broker.manager.streams.info(broker.names.dead)).state.messages>=1);
  const retried=await request(`/api/jobs/${fail.job.id}/retry`,{});assert.notEqual(retried.job.id,fail.job.id);assert.equal(retried.job.retry_of,fail.job.id);
  worker.kill('SIGTERM');await once(worker,'exit');
  const pending=await request('/api/jobs',{type:'delay',payload:{seconds:1}});
  await sleep(1000);assert.equal((await request(`/api/jobs/${pending.job.id}`)).status,'queued');
  const second=start('worker'), third=start('worker');
  await until(async()=> (await request('/api/workers')).items.filter(item=>item.fresh).length===2);
  const batches=await Promise.all(Array.from({length:6},()=>request('/api/jobs',{type:'delay',payload:{seconds:1}})));
  const completed=await until(async()=>{const values=await Promise.all(batches.map(job=>request(`/api/jobs/${job.job.id}`)));return values.every(job=>job.status==='completed')?values:false;});
  assert.equal(new Set(completed.map(job=>job.worker_id)).size,2);assert.ok(completed.every(job=>job.effectCount===1));
  const interrupted=await request('/api/jobs',{type:'delay',payload:{seconds:10}});
  const running=await until(async()=>{const value=await request(`/api/jobs/${interrupted.job.id}`);return value.status==='processing'?value:false;});
  const workers=(await request('/api/workers')).items.filter(item=>item.fresh);
  // Kill both test-only worker processes so the executing process is certainly interrupted.
  second.kill('SIGKILL');third.kill('SIGKILL');await Promise.all([once(second,'exit'),once(third,'exit')]);
  assert.ok(workers.some(item=>item.id===running.worker_id));start('worker');
  detail=await until(async()=>{const value=await request(`/api/jobs/${interrupted.job.id}`);return value.status==='completed'?value:false;},90000);
  assert.equal(detail.effectCount,1);assert.ok(detail.attempt_count>=2);
  assert.ok(detail.attempts.some(attempt=>attempt.status==='interrupted'));
  assert.equal(web.exitCode,null);
});
